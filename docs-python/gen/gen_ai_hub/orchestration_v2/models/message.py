"""
Defines message-related models for LLM-based conversations,
including system, user, assistant, tool, and developer messages.
"""

import json
import typing
from enum import Enum
from typing import Union, Optional, List

from pydantic import field_validator, ValidationError

from gen_ai_hub.orchestration_v2.models.base import ABCBaseModel as BaseModel
from gen_ai_hub.orchestration_v2.models.multimodal_items import ContentPart, ImageItem, TextPart, ImageUrl, ImagePart


class FunctionCall(BaseModel):
    """
    Represents a function call with its name and arguments.

    Attributes:
        name: str
            The name of the function to call.

        arguments: str
            The arguments to call the function with, as generated by the model in JSON
            format. Note that the model does not always generate valid JSON, and may
            hallucinate parameters not defined by your function schema. Validate the
            arguments in your code before calling your function.
    """
    name: str
    arguments: str

    def parse_arguments(self) -> dict:
        """Parses the arguments string as JSON.

        :return: A dictionary representing the parsed arguments.
        :rtype: dict
        """

        if self.arguments is None:
            return {}

        return json.loads(self.arguments)


class MessageToolCall(BaseModel):
    """
    The tool calls generated by the model, such as function calls.

    Attributes:
        id: The ID of the tool call.

        type: The type of the tool. Currently, only `function` is supported.

        function: The function that the model called.
    """
    id: str
    type: typing.Literal["function"] = "function"
    function: FunctionCall


class Role(str, Enum):
    """
    Enumerates supported roles in LLM-based conversations.

    This enum defines the standard roles used in interactions with Large Language Models (LLMs).
    These roles are generally used to structure the input and distinguish between different parts of the conversation.

    Values:
        USER: Represents the human user's input in the conversation.

        SYSTEM: Represents system-level instructions or context setting for the LLM.

        ASSISTANT: Represents the LLM's responses in the conversation.

        TOOL: Represents a tool or function that the LLM can call.

        DEVELOPER: Represents the developer's input or instructions in the conversation.
    """

    USER = "user"
    SYSTEM = "system"
    ASSISTANT = "assistant"
    TOOL = "tool"
    DEVELOPER = "developer"


class SystemMessage(BaseModel):
    """
    Represents a system message in a prompt or conversation template.

    System messages typically provide context or instructions to the AI model.

    Args:
        role: The role of the entity sending the message.

        content: The text content of the system message.
    """
    role: Role = Role.SYSTEM
    content: Union[str, List[TextPart]]


class UserMessage(BaseModel):
    """
    Represents a user message in a prompt or conversation template.

    User messages typically contain queries or inputs from the user.

    Args:
        role: The role of the entity sending the message.

        content: The message content, which may be plain text or a sequence of text and images.
    """
    role: Role = Role.USER
    content: Union[str, ContentPart, List[Union[str, ContentPart, ImageItem, ImagePart]]]

    @field_validator("content", mode="before")
    def content_validation(cls, content):  # pylint: disable=no-self-argument
        """
        Validates and maps the content field to the appropriate types.
        """

        mapped_content = []

        if isinstance(content, (str, ContentPart, dict)):
            mapped_content = content
        elif isinstance(content, list):
            for item in content:
                if isinstance(item, (ContentPart, dict)):
                    mapped_content.append(item)
                elif isinstance(item, str):
                    mapped_content.append(TextPart(text=item))
                elif isinstance(item, ImageItem):
                    mapped_content.append(ImagePart(image_url=ImageUrl(url=item.url, detail=item.detail)))
                else:
                    raise ValidationError("User message content list must contain only str or ImageItem")
        return mapped_content


class AssistantMessage(BaseModel):
    """
    Represents an assistant message in a prompt or conversation template.

    Assistant messages typically contain responses or outputs from the AI model.

    Args:
        role: The role of the entity sending the message.

        content: The text content of the assistant message.

        refusal: A string indicating refusal reason.

        tool_calls: A list of tool call objects.
    """
    role: Role = Role.ASSISTANT
    content: Optional[Union[str, List[TextPart]]] = None
    refusal: Optional[str] = None
    tool_calls: Optional[List[MessageToolCall]] = None


class ToolChatMessage(BaseModel):
    role: Role = Role.TOOL
    tool_call_id: str
    content: Union[str, List[TextPart]]


class DeveloperChatMessage(BaseModel):
    role: Role = Role.DEVELOPER
    content: Union[str, List[TextPart]]

class ResponseChatMessage(BaseModel):
    """
    Represents a response message in a conversation.


    Args:
        role: The role of the entity sending the message.

        content: The text content of the assistant message.

        refusal: A string indicating refusal reason.

        tool_calls: A list of tool call objects.
    """
    role: Role = Role.ASSISTANT
    content: str
    refusal: Optional[str] = None
    tool_calls: Optional[List[MessageToolCall]] = None

ChatMessage = Union[SystemMessage, UserMessage, AssistantMessage, ToolChatMessage, DeveloperChatMessage,
ResponseChatMessage]

__all__ = ["Role", "SystemMessage", "UserMessage", "AssistantMessage", "ToolChatMessage", "DeveloperChatMessage",
           "ChatMessage", "ResponseChatMessage", "FunctionCall", "MessageToolCall"]